#!/usr/bin/env python3
"""
arch_review_agent.py - AI Architecture Review Agent using CrewAI + Anthropic Claude.

Analyses the project structure and code patterns against defined architectural
guardrails and best practices. Outputs a review report.
"""

import argparse
import os
import sys
from pathlib import Path

from crewai import Agent, Crew, LLM, Process, Task


def collect_project_structure(root: str = ".") -> str:
    lines = []
    skip = {".venv", "__pycache__", ".git", "node_modules", ".pytest_cache", "reports"}
    for p in sorted(Path(root).rglob("*")):
        if any(s in p.parts for s in skip):
            continue
        indent = "  " * (len(p.relative_to(root).parts) - 1)
        lines.append(f"{indent}{p.name}{'/' if p.is_dir() else ''}")
    return "\n".join(lines[:100])


def collect_key_files(root: str = ".") -> str:
    key_patterns = ["app/src/*.py", "app/src/**/*.py", "Jenkinsfile", "docker-compose.yml", "pyproject.toml"]
    contents = []
    for pattern in key_patterns:
        for p in sorted(Path(root).glob(pattern))[:3]:
            try:
                text = p.read_text()[:1500]
                contents.append(f"### {p}\n```\n{text}\n```")
            except Exception:
                pass
    return "\n\n".join(contents)


def run_arch_review(output_path: str):
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        print("WARNING: ANTHROPIC_API_KEY not set - writing placeholder report", file=sys.stderr)
        Path(output_path).write_text("# Architecture Review\n\nAPI key not configured.")
        sys.exit(0)

    llm = LLM(
        model="anthropic/claude-3-5-sonnet-20241022",
        temperature=0.2,
        api_key=api_key
    )

    structure = collect_project_structure()
    key_files = collect_key_files()

    architect = Agent(
        role="Principal Software Architect",
        goal="Review project architecture against best practices and identify structural risks",
        backstory="""Principal architect with 15 years experience in microservices, clean architecture,
        and enterprise Python. You identify technical debt, boundary violations, and scalability risks.""",
        llm=llm,
        verbose=False
    )

    security_architect = Agent(
        role="Security Architect",
        goal="Identify architectural security risks and compliance gaps in the project structure",
        backstory="Security architect specializing in DevSecOps, pipeline security, and data protection.",
        llm=llm,
        verbose=False
    )

    lead = Agent(
        role="Engineering Lead",
        goal="Synthesize architecture and security findings into a prioritized action plan",
        backstory="Engineering lead who turns architect reviews into concrete, prioritized roadmaps.",
        llm=llm,
        verbose=False
    )

    structure_task = Task(
        description=f"""Review the project structure and code for architectural quality.

Project structure:
{structure}

Key file contents:
{key_files}

Evaluate:
1. Layer separation (API, service, repository, models)
2. Dependency direction (no upward dependencies)
3. Single responsibility per module
4. Configuration management approach
5. Scalability concerns
6. Test architecture and coverage structure

Output a bulleted list of findings.""",
        agent=architect,
        expected_output="Bulleted list of architectural findings"
    )

    security_task = Task(
        description=f"""Review the project for architectural security concerns.

Project structure:
{structure}

Evaluate:
1. Secret management approach (env vars, vaults)
2. Pipeline security gates (are they present and sufficient?)
3. Container security posture in docker-compose.yml
4. Authentication/authorization architecture
5. Data flow and PII handling
6. Dependency supply chain risks

Output a bulleted list of security architecture findings.""",
        agent=security_architect,
        expected_output="Bulleted list of security architecture findings"
    )

    synthesis_task = Task(
        description="""Synthesize the architecture and security findings into a final report.

Format EXACTLY as:

# Architecture Review Report

**Project:** AI-Governed SDLC PoC
**Reviewer:** AI Architecture Agent (CrewAI/Claude)

## Executive Summary
[3-4 sentence overall assessment for director/architect audience]

## Architecture Health Score: XX/100

## Strengths
[What is done well]

## Architecture Findings
[From architecture review - prioritised]

## Security Architecture Findings
[From security review - prioritised]

## Top 5 Recommendations
1. [Highest priority]
2.
3.
4.
5.

## Risk Register
| Risk | Severity | Mitigation |
|------|----------|------------|
[3-5 key risks]

---
*Generated by AI Architecture Review Agent*""",
        agent=lead,
        expected_output="Full markdown architecture review report",
        context=[structure_task, security_task]
    )

    crew = Crew(
        agents=[architect, security_architect, lead],
        tasks=[structure_task, security_task, synthesis_task],
        process=Process.sequential,
        verbose=False
    )

    print("Running AI architecture review...")
    result = crew.kickoff()

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text(str(result))
    print(f"Architecture review complete. Report: {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="AI Architecture Review Agent")
    parser.add_argument("--output", default="reports/arch-review.md")
    args = parser.parse_args()
    run_arch_review(args.output)
