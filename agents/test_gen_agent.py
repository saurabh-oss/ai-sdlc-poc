#!/usr/bin/env python3
"""
test_gen_agent.py - AI-powered test generation using CrewAI + Anthropic Claude.

Scans source files, understands function signatures and logic,
then generates pytest test files with meaningful coverage.
"""

import argparse
import ast
import os
import sys
from datetime import datetime
from pathlib import Path

from crewai import Agent, Crew, LLM, Process, Task


def extract_functions(filepath: str) -> list:
    try:
        source = Path(filepath).read_text()
        tree = ast.parse(source)
        functions = []
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not node.name.startswith("_"):
                    functions.append({
                        "name": node.name,
                        "args": [a.arg for a in node.args.args],
                        "docstring": ast.get_docstring(node) or "",
                        "line": node.lineno
                    })
        return functions
    except Exception:
        return []


def get_source_files(source_dir: str) -> list:
    return [
        str(p) for p in Path(source_dir).rglob("*.py")
        if "test" not in str(p) and "__pycache__" not in str(p)
    ]


def run_test_generation(source_dir: str, output_dir: str):
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        print("ERROR: ANTHROPIC_API_KEY not set", file=sys.stderr)
        sys.exit(1)

    llm = LLM(
        model="anthropic/claude-opus-5-5",
        temperature=0.1,
        api_key=api_key
    )

    source_files = get_source_files(source_dir)
    if not source_files:
        print("No source files found")
        return

    print(f"Found {len(source_files)} source files")

    test_engineer = Agent(
        role="Senior QA Engineer",
        goal="Generate comprehensive pytest test cases that provide high coverage and catch real bugs",
        backstory="Senior QA engineer and TDD practitioner with 10 years writing pytest suites.",
        llm=llm,
        verbose=False
    )

    Path(output_dir).mkdir(parents=True, exist_ok=True)

    for filepath in source_files[:10]:
        source_content = Path(filepath).read_text()
        functions = extract_functions(filepath)
        if not functions:
            continue

        relative_stem = Path(filepath).stem
        test_output = Path(output_dir) / f"test_{relative_stem}_generated.py"

        if test_output.exists():
            print(f"  Skipping {filepath} - test already exists")
            continue

        print(f"  Generating tests for: {filepath}")

        task = Task(
            description=f"""Generate a complete pytest test file for the following Python source.

Source file: {filepath}
Functions: {[f['name'] for f in functions]}

Source code:
```python
{source_content[:3000]}
```

Requirements:
1. Use correct relative imports for the project structure
2. Use pytest fixtures for setup/teardown
3. Use pytest-mock for mocking external dependencies
4. Write at least 2 tests per public function: happy path + error/edge case
5. Descriptive names: test_<function>_<scenario>_<expected>
6. Docstrings explaining what is tested
7. Do NOT hit real databases or external APIs

Output ONLY valid Python code with no markdown fences.""",
            agent=test_engineer,
            expected_output="Complete Python pytest test file as raw code"
        )

        crew = Crew(agents=[test_engineer], tasks=[task], process=Process.sequential, verbose=False)
        result = crew.kickoff()
        test_code = str(result).strip()

        if test_code.startswith("```"):
            test_code = "\n".join(test_code.split("\n")[1:])
        if test_code.endswith("```"):
            test_code = "\n".join(test_code.split("\n")[:-1])

        header = f"""# AUTO-GENERATED by AI Test Generation Agent
# Source: {filepath}
# Generated: {datetime.now().isoformat()}
# DO NOT EDIT - regenerate with: python agents/test_gen_agent.py --source {source_dir}

"""
        test_output.write_text(header + test_code)
        print(f"  Written: {test_output}")

    print(f"\nTest generation complete. Output: {output_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="AI Test Generation Agent")
    parser.add_argument("--source", default="app/src")
    parser.add_argument("--output", default="app/tests/generated")
    args = parser.parse_args()
    run_test_generation(args.source, args.output)
